"""Design aid for the A2 escalation rule, using the TUNING set only (odd rows).

    python scripts/a2_tuning_analysis.py

Simulates candidate rules from the Assignment 1 per-ticket answers of each model on the tuning
set: the small model answers every ticket, the rule accepts or escalates, escalated tickets take
the top model's Assignment 1 answer. For each candidate it reports the escalation fraction, the
simulated accuracy (overall and per category) against the top model on the same tuning tickets,
and a rough mean latency from the A1 accuracy-run latencies.

These are ESTIMATES for choosing a rule and its two settings. They are not results: every
reported A2 number must come from the test set, measured through the running cascade.
Writes a2/tuning-analysis.md.
"""

from a2_common import (A2, CATEGORIES, REPO, SHORT, TOP_MODEL, a1_latency, a1_predictions, fmt_pct, score,
                       split_rows)
from common import load_narratives

SMALL = ["llama3.2:1b-instruct-q4_K_M", "qwen2.5:0.5b"]
SOURCE = REPO / "ict3113_ticket_P1-3.xlsx"
OVERALL_DROP, CATEGORY_DROP = 0.10, 0.15


def mean(xs):
    return sum(xs) / len(xs) if xs else 0.0


def simulate(tuning, small_pred, large_pred, accept):
    """accept: row -> bool. Returns (predicted, escalated_rows)."""
    pred, esc = {}, []
    for r in tuning:
        if accept(r):
            pred[r] = small_pred[r]
        else:
            pred[r] = large_pred[r]
            esc.append(r)
    return pred, esc


def main():
    tuning = split_rows("tuning")
    rows = sorted(tuning)
    preds = {m: a1_predictions(m) for m in SMALL + [TOP_MODEL]}
    lat = {m: a1_latency(m) for m in SMALL + [TOP_MODEL]}
    narratives = load_narratives(SOURCE)
    length = {r: len(narratives[r]) for r in rows}
    large = preds[TOP_MODEL]
    top = score(tuning, large)
    L = mean([lat[TOP_MODEL][r] for r in rows])

    out = [
        "# Escalation-rule design aid (tuning set only)", "",
        "Generated by `scripts/a2_tuning_analysis.py` from the Assignment 1 per-ticket answers, **tuning set only** "
        f"({len(rows)} odd-row tickets). Escalated tickets take `{TOP_MODEL}`'s A1 answer. "
        "**These are estimates to help the team choose a rule and two settings, not results.** "
        "Reported numbers must come from the test set through the running cascade.", "",
        f"Reference on the tuning set: `{TOP_MODEL}` alone {top['right']}/{top['n']} = {fmt_pct(top['acc'])}; "
        f"mean A1 single-request latency {L / 1000:.2f} s.", "",
        "**Reading the tables:** *Esc* = escalation fraction. *Δ overall* = simulated accuracy minus the top model's on "
        "the same tickets (the limit allows −10). *Worst category* = largest per-category drop vs the top model "
        "(the limit allows −15). *Est. mean s* = mean over tickets of the A1 single-request latency of every model call "
        "that ticket would make (no queueing): small model (+ second small model for agreement) on every ticket, plus the "
        "top model on escalated tickets; for the length rule, long tickets make only the top-model call. "
        "The cascade is only faster than the top model alone when *Est. mean s* is below the top model's.", "",
    ]

    def row_for(name, small, pred, esc, extra_small=None, direct=False):
        """direct=True: escalated tickets skip the small model (length rule), so they cost only the large call."""
        s = score(tuning, pred)
        drops = [(c, s["per_category"][c]["acc"] - top["per_category"][c]["acc"]) for c in CATEGORIES
                 if top["per_category"][c]["n"]]
        worst = min(drops, key=lambda d: d[1])
        esc_set = set(esc)
        if direct:
            est = mean([lat[TOP_MODEL][r] if r in esc_set else lat[small][r] for r in rows])
        else:
            S = mean([lat[small][r] for r in rows]) + (mean([lat[extra_small][r] for r in rows]) if extra_small else 0)
            est = S + mean([lat[TOP_MODEL][r] if r in esc_set else 0 for r in rows])
        ok = (s["acc"] - top["acc"] >= -OVERALL_DROP - 1e-9) and all(d >= -CATEGORY_DROP - 1e-9 for _, d in drops)
        return (f"| {name} | {len(esc)}/{len(rows)} = {fmt_pct(len(esc) / len(rows))} | {s['right']}/{s['n']} = "
                f"{fmt_pct(s['acc'])} | {(s['acc'] - top['acc']) * 100:+.1f} | {SHORT[worst[0]]} {worst[1] * 100:+.1f} | "
                f"{est / 1000:.2f} | {'yes' if ok else 'no'} | {'yes' if est < L else 'no'} |")

    header = ["| Candidate | Esc | Simulated acc | Δ overall (pts) | Worst category (pts) | Est. mean s | Within limits? | Faster than top? |",
              "|---|---:|---:|---:|---|---:|---|---|"]

    for small in SMALL:
        sp = preds[small]
        out += [f"## Small model `{small}`", "", "### How reliable is each predicted category? (precision on tuning set)", "",
                "| Predicted category | Times predicted | Right | Precision |", "|---|---:|---:|---:|"]
        prec = {}
        for c in CATEGORIES:
            pr = [r for r in rows if sp[r] == c]
            k = sum(tuning[r] == c for r in pr)
            prec[c] = (k / len(pr)) if pr else None
            out.append(f"| {c} | {len(pr)} | {k} | {fmt_pct(prec[c])} |")
        small_alone = score(tuning, sp)
        out += ["", f"Small model alone on tuning set: {small_alone['right']}/{small_alone['n']} = {fmt_pct(small_alone['acc'])}.", ""]

        out += ["### Rule 1: category-based (accept when the predicted category is in the list)", ""] + header
        for t in (1.0, 0.9, 0.8, 0.7, 0.6, 0.5):
            acc_set = [c for c in CATEGORIES if prec[c] is not None and prec[c] >= t]
            pred, esc = simulate(tuning, sp, large, lambda r: sp[r] in acc_set)
            name = f"precision ≥ {t:.0%}: {', '.join(SHORT[c] for c in acc_set) or '(none)'}"
            out.append(row_for(name, small, pred, esc))
        out.append("")

        out += ["### Rule 2: ticket length (≤ N characters → small model; longer → straight to the top model)", ""] + header
        for cut in (200, 300, 400, 500, 600, 800):
            pred, esc = simulate(tuning, sp, large, lambda r: length[r] <= cut)
            out.append(row_for(f"≤ {cut} chars", small, pred, esc, direct=True))
        out.append("")

    a, b = SMALL
    out += [f"## Rule 3: agreement (`{a}` and `{b}` both answer; accept when they agree)", "",
            "Both small models are called on every ticket, so three models must be resident at once.", ""] + header
    agree_rows = [r for r in rows if preds[a][r] == preds[b][r]]
    out_detail = [f"They agree on {len(agree_rows)}/{len(rows)} tuning tickets; when they agree they are right on "
                  f"{sum(preds[a][r] == tuning[r] for r in agree_rows)}.", ""]
    pred, esc = simulate(tuning, preds[a], large, lambda r: preds[a][r] == preds[b][r])
    out.append(row_for("agree (any category)", a, pred, esc, extra_small=b))
    for excl in (["Credit card"], ["Credit card", "Credit reporting"]):
        pred, esc = simulate(tuning, preds[a], large,
                             lambda r, ex=excl: preds[a][r] == preds[b][r] and preds[a][r] not in ex)
        out.append(row_for(f"agree, excluding {', '.join(SHORT[c] for c in excl)}", a, pred, esc, extra_small=b))
    out += [""] + out_detail
    out += ["## Caveats", "",
            "- Tuning set is small (98 tickets; Debt collection has only 6), so differences of a few tickets are noise.",
            "- Latency estimates use A1 accuracy-run latencies (one request at a time, one model loaded). "
            "The A2 speed test measures the real figure under load.",
            "- The A2 per-category limit is measured on the test set, where Mortgage (9) and Credit card (7) are small.", ""]
    (A2 / "tuning-analysis.md").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
