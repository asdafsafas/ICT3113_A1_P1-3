"""Build the fixed Assignment 2 speed-test workload (rows outside the golden set).

    python scripts/a2_workload.py           # write a2/speed-workload/
    python scripts/a2_workload.py --check   # verify the committed files still match

Source: loadtest/data/tickets.tsv (rows 3200-3999, never part of the golden set).
Deterministic selection, so anyone can rebuild the same lists:
  * S tickets (3): the rows whose length is closest to the median length of rows 3200-3999
    (ties broken by row number). Used once to measure S on the top model.
  * Warm-up tickets (3): the next 3 rows closest to the median. Sent before every run; timings discarded.
  * Speed-test tickets: every other row from 3200 upward, in row order, first SPEED_COUNT of them.
    Contiguous rows keep the natural length mix, so the list contains typical and long tickets.
    Every configuration gets the same tickets in the same order (JMeter reads the file from the top).
"""

import argparse
import sys

from a2_common import REPO, WORKLOAD_DIR, percentile, read_tsv_tickets, write_tsv_tickets

SOURCE = REPO / "loadtest" / "data" / "tickets.tsv"
SPEED_COUNT = 200  # far more than one run sends (about 30-75 tickets), so no ticket repeats within a run


def build():
    tickets = read_tsv_tickets(SOURCE)
    rows = [r for r, _ in tickets]
    if rows != list(range(3200, 4000)):
        sys.exit(f"{SOURCE} must hold rows 3200-3999 in order")
    lengths = {r: len(t) for r, t in tickets}
    median = percentile(list(lengths.values()), 50)
    by_typical = sorted(rows, key=lambda r: (abs(lengths[r] - median), r))
    s_rows, warm_rows = sorted(by_typical[:3]), sorted(by_typical[3:6])
    used = set(s_rows) | set(warm_rows)
    speed_rows = [r for r in rows if r not in used][:SPEED_COUNT]
    text = dict(tickets)
    return {
        "s_tickets.tsv": [(r, text[r]) for r in s_rows],
        "warmup_tickets.tsv": [(r, text[r]) for r in warm_rows],
        "speed_tickets.tsv": [(r, text[r]) for r in speed_rows],
    }, lengths, median


def readme(files, lengths, median):
    all_len = sorted(lengths.values())
    sp = [lengths[r] for r, _ in files["speed_tickets.tsv"]]
    p90 = percentile(all_len, 90)

    def stats(v):
        return " | ".join(str(percentile(v, p)) for p in (5, 25, 50, 75, 95)) + f" | {max(v)}"

    def first(n):
        return [lengths[r] for r, _ in files["speed_tickets.tsv"][:n]]

    lines = [
        "# Assignment 2 speed-test workload", "",
        "Generated by `scripts/a2_workload.py` from `loadtest/data/tickets.tsv` (rows 3200-3999, outside the golden set). "
        "Do not edit by hand; rerun the script and check with `--check`.", "",
        "## Files", "",
        "| File | Rows | Use |", "|---|---|---|",
        f"| `s_tickets.tsv` | {', '.join(str(r) for r, _ in files['s_tickets.tsv'])} | Measure S on the top model (3 different typical tickets, one at a time) |",
        f"| `warmup_tickets.tsv` | {', '.join(str(r) for r, _ in files['warmup_tickets.tsv'])} | The 3 fixed warm-up tickets sent before every run; timings discarded |",
        f"| `speed_tickets.tsv` | {files['speed_tickets.tsv'][0][0]}-{files['speed_tickets.tsv'][-1][0]} ({len(sp)} rows, S and warm-up rows skipped) | JMeter workload, same order for every configuration |",
        "",
        f"Typical length = closest to the median length of rows 3200-3999 ({median} characters).",
        "",
        "## Length mix (characters)", "",
        "| Set | p5 | p25 | p50 | p75 | p95 | max |", "|---|---|---|---|---|---|---|",
        f"| All rows 3200-3999 | {stats(all_len)} |",
        f"| Speed list, all {len(sp)} | {stats(sp)} |",
        f"| Speed list, first 30 (one run at S ≥ 5) | {stats(first(30))} |",
        f"| Speed list, first 50 (one run at S ≈ 3) | {stats(first(50))} |",
        "",
        f"Long tickets (above the p90 of all rows, {p90} chars): {sum(x > p90 for x in first(30))} of the first 30, "
        f"{sum(x > p90 for x in first(50))} of the first 50.",
        "",
        "## Row numbers used as the speed-test workload (supporting file required by the brief)", "",
        ", ".join(str(r) for r, _ in files["speed_tickets.tsv"]),
        "",
        "A run uses the list from the top; only the first *n* rows are sent, where *n* is the number of arrivals in that run "
        "(recorded per run in the JTL `row` column).", "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    files, lengths, median = build()
    text = readme(files, lengths, median)
    if args.check:
        stale = []
        for name, tickets in files.items():
            p = WORKLOAD_DIR / name
            if not p.exists() or read_tsv_tickets(p) != tickets:
                stale.append(name)
        if not (WORKLOAD_DIR / "README.md").exists() or (WORKLOAD_DIR / "README.md").read_text(encoding="utf-8") != text:
            stale.append("README.md")
        if stale:
            sys.exit("Speed workload out of date or missing: " + ", ".join(stale))
        print("OK: speed workload matches loadtest/data/tickets.tsv")
        return
    for name, tickets in files.items():
        write_tsv_tickets(WORKLOAD_DIR / name, tickets)
    (WORKLOAD_DIR / "README.md").write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {WORKLOAD_DIR.relative_to(REPO)}: S rows {[r for r, _ in files['s_tickets.tsv']]}, "
          f"warm-up rows {[r for r, _ in files['warmup_tickets.tsv']]}, {len(files['speed_tickets.tsv'])} speed rows")


if __name__ == "__main__":
    main()
