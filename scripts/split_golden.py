"""Split the frozen golden set into the Assignment 2 tuning and test sets.

    python scripts/split_golden.py           # write a2/golden-split/
    python scripts/split_golden.py --check   # verify the committed split still matches

Rule from the Assignment 2 brief (Step 1): sort the golden-set tickets by row number;
odd rows are the tuning set, even rows are the test set. The tuning set is used to design
the escalation rule; every reported accuracy number comes from the test set only.

The golden set itself (golden/golden_set.csv) is frozen at tag `prediction-freeze` and is
only read here, never modified. The source file's SHA-256 is recorded in SPLIT.md so the
split can be traced to the frozen labels.
"""
import argparse
import csv
import hashlib
import io
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "golden" / "golden_set.csv"
OUT = ROOT / "a2" / "golden-split"
CATEGORIES = [
    "Credit reporting",
    "Debt collection",
    "Mortgage",
    "Credit card",
    "Bank account or service",
    "Consumer loan",
    "Money transfer or service",
]


def load():
    with open(SOURCE, encoding="utf-8-sig", newline="") as f:
        rows = list(csv.DictReader(f))
    rows.sort(key=lambda r: int(r["row"]))
    bad = [r["row"] for r in rows if r["label"] not in CATEGORIES]
    if bad:
        sys.exit(f"Unexpected labels in rows: {', '.join(bad)}")
    if len({r["row"] for r in rows}) != len(rows):
        sys.exit("Duplicate row numbers in the golden set")
    return rows


def to_csv(rows):
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["row", "label"])
    for r in rows:
        w.writerow([r["row"], r["label"]])
    return buf.getvalue()


def summary(tuning, test, sha):
    t_counts, s_counts = Counter(r["label"] for r in tuning), Counter(r["label"] for r in test)
    lines = [
        "# Assignment 2 golden-set split",
        "",
        "Generated by `scripts/split_golden.py`. Do not edit by hand; rerun the script and check with `--check`.",
        "",
        "**Rule (A2 brief, Step 1):** golden-set tickets sorted by row number; **odd rows = tuning set**, "
        "**even rows = test set**. The tuning set is used to design and adjust the escalation rule. "
        "Every reported A2 accuracy number uses the test set only.",
        "",
        f"**Source:** `golden/golden_set.csv`, unchanged since tag `prediction-freeze`. "
        f"SHA-256 `{sha}`.",
        "",
        "**Caveat (from the brief):** every model already ran on the full golden set in Assignment 1, so the test "
        "set is not new data. It gives a fair comparison of all configurations on the same tickets, with the "
        "cascade rule not tuned on them.",
        "",
        "| Category | Tuning (odd rows) | Test (even rows) |",
        "|---|---:|---:|",
    ]
    for c in CATEGORIES:
        lines.append(f"| {c} | {t_counts[c]} | {s_counts[c]} |")
    lines.append(f"| **Total** | **{len(tuning)}** | **{len(test)}** |")
    lines += [
        "",
        "## Small categories",
        "",
        "On the test set, one ticket is worth 100 ÷ n points of a category's accuracy. "
        "The brief asks the report to say when a category is too small for the per-category limit "
        "(top model − 15 points) to be a fair test. Our working cut-off (a team choice, not from the brief): "
        "a category is too small when a single ticket is worth more than 10 points.",
        "",
        "| Category | Test n | Points per ticket | Fair per-category test? |",
        "|---|---:|---:|---|",
    ]
    for c in CATEGORIES:
        n = s_counts[c]
        pts = 100 / n
        lines.append(f"| {c} | {n} | {pts:.1f} | {'No: one ticket is worth more than 10 points' if pts > 10 else 'Yes'} |")
    lines += [
        "",
        f"Tuning-set categories under 10 tickets: "
        + (", ".join(f"{c} ({t_counts[c]})" for c in CATEGORIES if t_counts[c] < 10) or "none")
        + ". Rules that depend on these categories rest on very few tickets.",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify committed files instead of writing them")
    args = ap.parse_args()

    sha = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    rows = load()
    tuning = [r for r in rows if int(r["row"]) % 2 == 1]
    test = [r for r in rows if int(r["row"]) % 2 == 0]
    files = {
        OUT / "tuning_set.csv": to_csv(tuning),
        OUT / "test_set.csv": to_csv(test),
        OUT / "SPLIT.md": summary(tuning, test, sha),
    }

    if args.check:
        stale = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        if stale:
            sys.exit("Split out of date or missing: " + ", ".join(str(p.relative_to(ROOT)) for p in stale))
        print(f"OK: split matches golden set (tuning {len(tuning)}, test {len(test)}, sha256 {sha[:12]})")
        return

    OUT.mkdir(parents=True, exist_ok=True)
    for p, text in files.items():
        p.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.relative_to(ROOT)}: tuning {len(tuning)}, test {len(test)} (sha256 {sha[:12]})")


if __name__ == "__main__":
    main()
