"""Assignment 2 Step 1: accuracy limits, and single-model accuracy on the test set.

    python scripts/a2_limits.py

Re-scores the Assignment 1 per-ticket accuracy runs (results/accuracy/*.csv) on the TEST set only
(even rows, a2/golden-split/test_set.csv). The brief allows this reuse for single models when the
digest, prompt, Ollama version and machine are unchanged; the report states that it was done.

  overall limit       = top model's test-set accuracy - 10 points
  per-category limit  = top model's test-set accuracy on that category - 15 points

Writes a2/limits.json (read by the A2 accuracy report) and a2/limits.md.
"""

import json

from a2_common import (A1_RUNS, A2, CATEGORIES, LIMITS_JSON, REPO, TOP_MODEL, a1_predictions, fmt_pct, read_csv,
                       score, split_rows)
from a2_common import A1_ACCURACY

OVERALL_DROP, CATEGORY_DROP = 0.10, 0.15
SMALL_N_POINTS = 10  # team choice: a category is "too small" when one ticket is worth more than this many points


def main():
    test = split_rows("test")
    scores = {m: score(test, a1_predictions(m)) for m in A1_RUNS}
    top = scores[TOP_MODEL]
    limits = {
        "source": "Assignment 1 accuracy runs re-scored on a2/golden-split/test_set.csv",
        "top_model": TOP_MODEL,
        "top_model_run": A1_RUNS[TOP_MODEL],
        "test_tickets": top["n"],
        "top_overall": {"right": top["right"], "n": top["n"], "acc": top["acc"]},
        "overall_limit": top["acc"] - OVERALL_DROP,
        "per_category": {},
    }
    for c in CATEGORIES:
        p = top["per_category"][c]
        limits["per_category"][c] = {"n": p["n"], "top_right": p["right"], "top_acc": p["acc"],
                                     "limit": p["acc"] - CATEGORY_DROP,
                                     "too_small": p["n"] == 0 or 100 / p["n"] > SMALL_N_POINTS}
    digests = {m: read_csv(A1_ACCURACY / f)[0]["model_digest"] for m, f in A1_RUNS.items()}

    def passes(s):
        ok_overall = s["acc"] >= limits["overall_limit"] - 1e-9
        fails = [c for c in CATEGORIES if s["per_category"][c]["acc"] < limits["per_category"][c]["limit"] - 1e-9]
        return ok_overall, fails

    lines = [
        "# Assignment 2 accuracy limits", "",
        "Generated by `scripts/a2_limits.py`. Single-model results **reuse the Assignment 1 accuracy runs** "
        "(same model digests, prompt `classify_v1.txt`, Ollama 0.35.1 and machine), re-scored on the "
        f"**test set only** ({top['n']} tickets, even rows). The brief allows this reuse; the report must say it was done.", "",
        f"**Top model:** `{TOP_MODEL}`, test-set accuracy **{top['right']}/{top['n']} = {fmt_pct(top['acc'])}**.", "",
        f"**Overall limit = {fmt_pct(top['acc'])} − 10 points = {fmt_pct(limits['overall_limit'])}**.", "",
        "## Per-category limits (top model − 15 points)", "",
        "| Category | Test n | Top model right | Top model acc | Limit | Fair test? |", "|---|---:|---:|---:|---:|---|",
    ]
    for c in CATEGORIES:
        p = limits["per_category"][c]
        lines.append(f"| {c} | {p['n']} | {p['top_right']} | {fmt_pct(p['top_acc'])} | {fmt_pct(p['limit'])} | "
                     f"{'No: one ticket = ' + format(100 / p['n'], '.1f') + ' points' if p['too_small'] else 'Yes'} |")
    lines += ["", f"Small-category cut-off (team choice): one ticket worth more than {SMALL_N_POINTS} points.", "",
              "## Single models on the test set", "",
              "| Model | Digest | Overall | Overall limit | Categories below limit | Passes both? |",
              "|---|---|---:|---|---|---|"]
    for m, s in scores.items():
        ok, fails = passes(s)
        lines.append(f"| `{m}` | `{digests[m][:12]}` | {s['right']}/{s['n']} = {fmt_pct(s['acc'])} | {'PASS' if ok else 'FAIL'} | "
                     f"{', '.join(fails) if fails else 'none'} | **{'YES' if ok and not fails else 'NO'}** |")
    lines += ["", "## Per-category accuracy, test set (right/n)", "",
              "| Category | " + " | ".join(f"`{m}`" for m in scores) + " |", "|---|" + "---:|" * len(scores)]
    for c in CATEGORIES:
        lines.append(f"| {c} | " + " | ".join(
            f"{s['per_category'][c]['right']}/{s['per_category'][c]['n']} ({fmt_pct(s['per_category'][c]['acc'])})"
            for s in scores.values()) + " |")
    lines += ["", "Per the brief, single models that fail the accuracy limits do not need a speed test. "
                  "The top model and the cascade are speed-tested in all cases.", ""]

    limits["single_models"] = {m: {"right": s["right"], "n": s["n"], "acc": s["acc"], "digest": digests[m],
                                   "passes": passes(s)[0] and not passes(s)[1]} for m, s in scores.items()}
    LIMITS_JSON.write_text(json.dumps(limits, indent=2) + "\n", encoding="utf-8", newline="\n")
    (A2 / "limits.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("\n".join(lines))
    print(f"Wrote {LIMITS_JSON.relative_to(REPO)} and a2/limits.md")


if __name__ == "__main__":
    main()
